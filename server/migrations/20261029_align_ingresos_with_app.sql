BEGIN;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.ingresos) THEN
    RAISE EXCEPTION
      'La tabla ingresos ya tiene registros. Migra esos datos manualmente antes de aplicar esta migración.';
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'ingresos'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE public.ingresos
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

ALTER TABLE public.ingresos
  ADD COLUMN usuario_id INTEGER NOT NULL
  REFERENCES public.users(id);

ALTER TABLE public.ingresos
  DROP COLUMN cliente;

COMMIT;
